#!/usr/bin/env python3
"""Generate the Postgres schema and layout files from copybooks (copybook is the schema — never hand-edit outputs).

Inputs : migration/datasets.json (dataset → copybook, table), vendor copybooks, CardDemo IDCAMS JCL (keys).
Outputs: migration/layouts/<COPYBOOK>.json            record layouts (also read by the Java codec)
         migration/layouts/datasets.json              dataset → table, layout, primary key columns, lrecl
         modern/batch/src/main/resources/db/schema.sql generated DDL

Type mapping (ADR 0006):
  X(n)            → char(n) COLLATE "C"   byte order = oracle's ASCII key order
  9(n)            → numeric(n,0)
  S9(n)V9(m)      → numeric(n+m,m)        sign from overpunch on load, re-encoded on unload
  FILLER          → bytea                 opaque, byte-exact: fillers hold spaces, '0's or X'00' (uninitialized WS)
  flat datasets   → extra seq integer PK  preserves record order
Usage: gen_schema.py [ROOT=.]
"""
import importlib.util, json, sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
sys.path.insert(0, str(ROOT / "migration"))
import copybook  # noqa: E402

CPY = ROOT / "vendor/carddemo/app/cpy"
OUT_L = ROOT / "migration/layouts"
OUT_SQL = ROOT / "modern/batch/src/main/resources/db/schema.sql"


def catalog():
    spec = importlib.util.spec_from_file_location("vsamload", ROOT / "legacy/vsam/load.py")
    mod = importlib.util.module_from_spec(spec)
    argv, sys.argv = sys.argv, ["load.py", str(ROOT)]
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.argv = argv
    return mod.parse_catalog(ROOT / "vendor/carddemo/app/jcl")


def sql_type(f):
    if f["filler"]:
        return "bytea"   # opaque padding: may hold '0's, spaces or X'00' (uninitialized storage) — kept byte-exact
    if f["kind"] == "X":
        return f'char({f["length"]}) COLLATE "C"'
    if f["kind"] in ("9", "S9", "P"):
        return f'numeric({f["digits"]},{f["scale"]})'
    raise ValueError(f"no SQL mapping for kind {f['kind']} ({f['name']})")


def key_columns(layout, off, ln):
    cols = [f for f in layout["fields"] if f["offset"] >= off and f["offset"] + f["length"] <= off + ln]
    if sum(f["length"] for f in cols) != ln or (cols and cols[0]["offset"] != off):
        raise ValueError(f"{layout['copybook']}: key ({ln},{off}) does not align with field boundaries")
    return [f["column"] for f in cols]


def main():
    cfg = {k: v for k, v in json.loads((ROOT / "migration/datasets.json").read_text()).items() if not k.startswith("_")}
    cat = catalog()
    OUT_L.mkdir(parents=True, exist_ok=True)
    ddl = ["-- GENERATED by migration/gen_schema.py from CardDemo copybooks + IDCAMS key definitions.",
           "-- Do not edit. Regenerate: make db-schema", "SET client_min_messages = warning;", ""]
    index = {}
    for dsn, d in cfg.items():
        flat = d.get("flat", False)
        lrecl = None if flat else cat[dsn]["lrecl"]
        lay = copybook.parse(CPY / f"{d['copybook']}.cpy", lrecl)
        (OUT_L / f"{d['copybook']}.json").write_text(json.dumps(lay, indent=1) + "\n")
        if flat:
            pk = ["seq"]
        else:
            c = cat[dsn]
            pk = key_columns(lay, c["key_off"], c["key_len"])
        seed = dsn if flat else cat[dsn]["seed"]  # flat dataset is its own seed; KSDS seed = REPRO source in JCL
        index[dsn] = {"table": d["table"], "copybook": d["copybook"], "lrecl": lay["lrecl"], "pk": pk,
                      "flat": flat, "seed": seed, "drop_placeholder": d.get("drop_placeholder", False),
                      "key": None if flat else [cat[dsn]["key_off"], cat[dsn]["key_len"]]}
        cols = (["  seq integer NOT NULL"] if flat else []) + [
            f'  {f["column"]} {sql_type(f)} NOT NULL' for f in lay["fields"]]
        cols.append(f"  PRIMARY KEY ({', '.join(pk)})")
        ddl.append(f"-- {dsn}  ({d['copybook']}, LRECL {lay['lrecl']}"
                   + ("" if flat else f", KSDS KEYS({cat[dsn]['key_len']} {cat[dsn]['key_off']})") + ")")
        ddl.append(f'DROP TABLE IF EXISTS "{d["table"]}";')
        ddl.append(f'CREATE TABLE "{d["table"]}" (\n' + ",\n".join(cols) + "\n);")
        ddl.append(f"COMMENT ON TABLE \"{d['table']}\" IS 'Dataset {dsn}; copybook {d['copybook']}; record {lay['record']}';")
        for f in lay["fields"]:
            note = "legacy padding, kept for byte parity" if f["filler"] else f["name"]
            ddl.append(f"COMMENT ON COLUMN \"{d['table']}\".{f['column']} IS "
                       f"'{note}: PIC {f['pic']} @{f['offset']} len {f['length']}';")
        ddl.append("")
    (OUT_L / "datasets.json").write_text(json.dumps(index, indent=1) + "\n")
    OUT_SQL.parent.mkdir(parents=True, exist_ok=True)
    OUT_SQL.write_text("\n".join(ddl))
    for dsn, i in index.items():
        print(f"{i['table']:18} {i['copybook']}  lrecl={i['lrecl']:3}  pk={','.join(i['pk'])}")


if __name__ == "__main__":
    main()
